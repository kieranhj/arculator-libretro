#!/usr/bin/env python3
"""Embed the small data files the emulator expects beside its executable.

Arculator looks for cmos/<set>/cmos.bin (factory CMOS contents per ROM
generation) and roms/arcrom_ext (the support ROM) relative to its base
directory, and rom_load_arc_support_extrom() does not check that the file
opened. The core seeds these into the RetroArch system directory on first run
from the copies embedded here, which come from the Arculator tree.

  gen_data.py <arculator-tree> <out.h>
"""
import os
import sys

FILES = [
    ("cmos/arthur/cmos.bin", "cmos_arthur"),
    ("cmos/riscos2/cmos.bin", "cmos_riscos2"),
    ("cmos/riscos3_old/cmos.bin", "cmos_riscos3_old"),
    ("cmos/riscos3_new/cmos.bin", "cmos_riscos3_new"),
    ("roms/arcrom_ext", "arcrom_ext"),
    # The drive-noise samples are not optional: ddnoise_mix() is what re-arms
    # the floppy controller's timer at the end of a multi-track seek, and it
    # indexes these samples without checking that they loaded.
    ("ddnoise/35/motor.wav", "dd_motor"),
    ("ddnoise/35/motoron.wav", "dd_motoron"),
    ("ddnoise/35/motoroff.wav", "dd_motoroff"),
    ("ddnoise/35/stepi.wav", "dd_stepi"),
    ("ddnoise/35/stepo.wav", "dd_stepo"),
    ("ddnoise/35/seek1i.wav", "dd_seek1i"),
    ("ddnoise/35/seek1o.wav", "dd_seek1o"),
    ("ddnoise/35/seek2i.wav", "dd_seek2i"),
    ("ddnoise/35/seek2o.wav", "dd_seek2o"),
    ("ddnoise/35/seek3i.wav", "dd_seek3i"),
    ("ddnoise/35/seek3o.wav", "dd_seek3o"),
]


def main():
    root, out = sys.argv[1], sys.argv[2]
    with open(out, "w") as f:
        f.write("/* Generated by gen_data.py; do not edit. */\n")
        f.write("#include <stddef.h>\n#include <stdint.h>\n\n")
        for rel, name in FILES:
            data = open(os.path.join(root, rel), "rb").read()
            f.write("static const uint8_t %s[%d] = {\n" % (name, len(data)))
            for i in range(0, len(data), 16):
                f.write("  " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
            f.write("};\n\n")
        f.write("static const struct { const char* p_path; const uint8_t* p_data; size_t len; } s_seed_files[] = {\n")
        for rel, name in FILES:
            f.write('  { "%s", %s, sizeof(%s) },\n' % (rel, name, name))
        f.write("};\n")


if __name__ == "__main__":
    main()
